# Function Overload:
print(len("Gustavo")) # = 7
print(len(["Sandy", "Junior"])) # = 2
print(len({"a": "y", "b": "y"})) # = 2
# Mesma função, comportamentos diferentes...


# Operator Overload:
print(+5)  # 5 positivo (Torna valor positivo)
print(5 + 4)  # Soma
print("Poli" + "Morfo")  # Concatenação
print([3, 5] + [2, 4])  # Junta listas
# Mesmo operador, resultados diferentes...
